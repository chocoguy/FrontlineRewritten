#!/usr/bin/env python3
"""Write the native game library's source list as a CMake file.

The decomp's configure.py is the one list of game units. This script reads the
libraries the native build compiles from it, drops the units the port replaces,
and writes a CMake file defining FRONTLINE_GAME_SOURCES (and
FRONTLINE_GAME_EXCLUDED, for reports). CMake runs it at configure time, so a
unit added to the decomp shows up in the native build without editing this repo.

    python3 tools/gen_sources.py <decomp dir> <output .cmake>
"""

import re
import sys
from pathlib import Path

# Libraries from configure.py that the native build compiles. The rest
# (Dolphin SDK, MSL, Runtime, TRK, ...) is GameCube system code that the
# platform layer replaces.
NATIVE_LIBS = ["Game", "Movie", "EA System", "EA Sound"]

# Units in those libraries that the port doesn't compile, and why.
EXCLUDED = {
    "game/loadelf.cpp": "boot loader: loads the game ELF from disc",
    "game/dvdStatus_base.c": "disc-error screen: there's no disc drive",
    "ea/sys/debugger.cpp": "debugger hooks for the GameCube dev kit",
    "movie/gc_idct.asm": "paired-single assembly; Phase 1 replaces it with C",
}


OBJECT = re.compile(r'Object\(\s*\w+\s*,\s*"([^"]+)"([^)]*)\)')
# A library opens either as a dict ("lib": "<name>") or through a helper that
# takes the name first (DolphinLib("<name>", ...), Rel("<name>", ...)).
LIB_START = re.compile(r'"lib":\s*"([^"]+)"|\b(?:DolphinLib|Rel)\(\s*"([^"]+)"')


def units(configure_py: Path) -> dict:
    """Map each library name to its units, as (path, compiled_as_cxx) pairs."""
    text = configure_py.read_text()
    starts = [(m.start(), m.group(1) or m.group(2)) for m in LIB_START.finditer(text)]
    libs = {}
    for i, (pos, name) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(text)
        # Many .c units are built as C++ ("-lang=c++"); clang has to match.
        libs[name] = [(m.group(1), "-lang=c++" in m.group(2))
                      for m in OBJECT.finditer(text, pos, end)]
    return libs


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    decomp, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2])
    libs = units(decomp / "configure.py")

    missing = [lib for lib in NATIVE_LIBS if lib not in libs]
    if missing:
        sys.exit(f"configure.py has no libraries named {missing}")

    sources, as_cxx, excluded = [], [], []
    for lib in NATIVE_LIBS:
        for unit, cxx in libs[lib]:
            if unit in EXCLUDED:
                excluded.append(unit)
                continue
            sources.append(unit)
            if cxx and unit.endswith(".c"):
                as_cxx.append(unit)

    stale = sorted(set(EXCLUDED) - set(excluded))
    if stale:
        sys.exit(f"gen_sources.py excludes units configure.py doesn't list: {stale}")

    lines = ["# Generated by tools/gen_sources.py from the decomp's configure.py. Don't edit.", ""]
    lines.append("set(FRONTLINE_GAME_SOURCES")
    lines += [f"    src/{u}" for u in sources]
    lines.append(")")
    lines.append("")
    lines.append("# .c units the GameCube build compiles as C++.")
    lines.append("set(FRONTLINE_GAME_CXX_C_SOURCES")
    lines += [f"    src/{u}" for u in as_cxx]
    lines.append(")")
    lines.append("")
    lines.append("set(FRONTLINE_GAME_EXCLUDED")
    lines += [f"    src/{u}  # {EXCLUDED[u]}" for u in excluded]
    lines.append(")")
    content = "\n".join(lines) + "\n"

    # Only touch the file when it changes, so CMake doesn't reconfigure for nothing.
    if not out.exists() or out.read_text() != content:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content)


if __name__ == "__main__":
    main()
